const FN = 'http://localhost:8000';
let pass = 0, fail = 0;
const ok = (c: boolean, n: string, x?: unknown) => { if (c) { pass++; console.log('  PASS', n); } else { fail++; console.log('  FAIL', n, JSON.stringify(x ?? '')); } };
const call = async (who: string | null, body: any) => {
  const r = await fetch(FN, { method: 'POST', headers: { 'Content-Type': 'application/json', ...(who ? { Authorization: 'Bearer user:' + who } : {}) }, body: JSON.stringify(body) });
  return { status: r.status, body: await r.json() };
};
const CLS = '11111111-1111-1111-1111-111111111111';
const base = { action: 'new_learner', classId: CLS, name: '  Ndapewa   Shikongo ', phone: '081 234 5678' };
let r = await call(null, base);
ok(r.status === 401, 'signed-out request refused', r);
r = await call('other', base);
ok(r.status === 403, 'a teacher of another class cannot add learners', r);
r = await call('tch', { ...base, phone: '12345' });
ok(r.status === 400 && /Namibian mobile/.test(r.body.error), 'invalid mobile number refused', r);
r = await call('tch', { ...base, name: 'A' });
ok(r.status === 400, 'missing name refused', r);
r = await call('tch', base);
ok(r.status === 200 && /^K12-NA-[A-Z0-9]{6}$/.test(r.body.learnerUid) && r.body.name === 'Ndapewa Shikongo', 'teacher creates a basic-phone learner and gets a k12plus ID', r);
let st = await (await fetch('http://localhost:9997/__state')).json();
const p = st.profiles.find((x: any) => x.learner_uid === r.body.learnerUid);
ok(p && p.role === 'learner' && p.grade === 11 && p.school_id === 'S1' && p.phone_e164 === '264812345678', 'account has learner role, class grade, class school and normalised phone', p);
ok(st.enrolments.length === 1 && st.enrolments[0].joined_via === 'teacher' && st.enrolments[0].enrolled_by === 'tch', 'learner is enrolled in the class, recorded as added by the teacher', st.enrolments);
ok(st.users[0].email.endsWith('@learners.k12edu.io') && st.users[0].password.length === 24, 'private sign-in address and a random password nobody sees');
r = await call('tch', { ...base, name: 'Tuyeni Shikongo' });
ok(r.status === 200, 'a sibling on the same shared phone can be added', r);
r = await call('tch', { ...base, name: 'selma nangolo', phone: '+264 81 333 4444' });
ok(r.status === 409 && /K12-NA-OLD111/.test(r.body.error), 'same name on the same phone points the teacher to the existing account', r);
r = await call('adm', { ...base, name: 'Admin Added', phone: '0851112222' });
ok(r.status === 200, 'an administrator can add learners to any class (TN Mobile 085 number)', r);
await fetch('http://localhost:9997/__failEnrol');
r = await call('tch', { ...base, name: 'Will Fail' });
st = await (await fetch('http://localhost:9997/__state')).json();
ok(r.status === 500 && st.deleted.length === 1, 'if enrolment fails, the half-made account is removed again', st.deleted);
console.log(`\n${pass} passed, ${fail} failed`);
Deno.exit(fail ? 1 : 0);
